// Writes src/audio/voiceManifest.generated.ts: line key -> bundled clip.
// Includes every content line plus the private whole-sentence name clips.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const lines: { key: string; text: string }[] = JSON.parse(readFileSync('tools/out/lines.json', 'utf8'));
const extra: string[] = existsSync('tools/out/clip-keys.json') ? JSON.parse(readFileSync('tools/out/clip-keys.json', 'utf8')) : [];
const keys = [...new Set([...lines.map((l) => l.key), ...extra])].filter((k) => existsSync(`assets/audio/voice/${k}.m4a`));
const body = keys.map((k) => `  '${k}': require('../../assets/audio/voice/${k}.m4a'),`).join('\n');
writeFileSync(
  'src/audio/voiceManifest.generated.ts',
  `// Generated by tools/gen-manifest.ts. ${keys.length} clips.\nexport const VOICE: Record<string, number> = {\n${body}\n};\nexport const VOICE_TEXT: Record<string, string> = ${JSON.stringify(Object.fromEntries(lines.map((l) => [l.key, l.text])))};\n`,
);
const missing = lines.filter((l) => !existsSync(`assets/audio/voice/${l.key}.m4a`));
console.log(`manifest: ${keys.length} clips; content lines missing a clip: ${missing.length}`);
if (missing.length) process.exitCode = 1;
