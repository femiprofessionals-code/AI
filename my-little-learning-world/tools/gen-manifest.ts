// Writes src/audio/voiceManifest.generated.ts: line key -> bundled clip.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const lines: { key: string; text: string }[] = JSON.parse(readFileSync('tools/out/lines.json', 'utf8'));
const present = lines.filter((l) => existsSync(`assets/audio/voice/${l.key}.m4a`));
const body = present.map((l) => `  '${l.key}': require('../../assets/audio/voice/${l.key}.m4a'),`).join('\n');
writeFileSync(
  'src/audio/voiceManifest.generated.ts',
  `// Generated by tools/gen-manifest.ts. ${present.length} of ${lines.length} lines have clips.\nexport const VOICE: Record<string, number> = {\n${body}\n};\nexport const VOICE_TEXT: Record<string, string> = ${JSON.stringify(Object.fromEntries(lines.map((l) => [l.key, l.text])))};\n`,
);
console.log(`manifest: ${present.length}/${lines.length} clips`);
if (present.length < lines.length) process.exitCode = 1;
