// Bundles the family's private starter media (never committed to git) into
// the build. Reads private/profile.json; writes assets/private/* and
// src/private.generated.ts. With no private folder it writes an empty stub,
// so the app still builds and asks the parent to add a name and photo.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

type Profile = {
  childName: string;
  nameClip?: string;
  photo?: { file: string; width: number; height: number; markers: Record<string, { x: number; y: number; r: number } | null> };
};

const out = 'src/private.generated.ts';
mkdirSync('assets/private', { recursive: true });

if (!existsSync('private/profile.json')) {
  writeFileSync(out, 'export const STARTER = { childName: \'\', nameClip: null as any, photo: null as any };\n');
  console.log('No private profile: wrote empty stub.');
  process.exit(0);
}

const p: Profile = JSON.parse(readFileSync('private/profile.json', 'utf8'));
let nameClip = 'null';
if (p.nameClip) {
  copyFileSync(`private/${p.nameClip}`, 'assets/private/name.m4a');
  nameClip = "require('../assets/private/name.m4a')";
}
let photo = 'null';
if (p.photo) {
  copyFileSync(`private/${p.photo.file}`, 'assets/private/photo.jpg');
  photo = `{ source: require('../assets/private/photo.jpg'), width: ${p.photo.width}, height: ${p.photo.height}, markers: ${JSON.stringify(p.photo.markers)} }`;
}
writeFileSync(
  out,
  `// Generated by tools/prepare-private.ts. Do not commit.\nexport const STARTER = {\n  childName: ${JSON.stringify(p.childName)},\n  nameClip: ${nameClip} as any,\n  photo: ${photo} as any,\n};\n`,
);
console.log('Private starter profile bundled for', p.childName);
